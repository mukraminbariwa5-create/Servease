"""Real-browser checks of the Servease app shell on a phone and a laptop:
login-first entry (splash, intro, welcome, account type), tab bar, banner carousel, categories, service and pro lists, filter sheet, payment screen, fonts, layout overflow and dark mode.
Run against a freshly installed demo database:  php database/install.php && python3 tests/test_ui.py
"""
import os, asyncio
from playwright.async_api import async_playwright

B = os.environ.get('SERVEASE_URL', 'http://127.0.0.1:8000').rstrip('/')
res = []
def check(c, m): res.append(('✓' if c else '✗') + ' ' + m)

PAGES_GUEST = ['/welcome', '/login', '/register', '/register?role=client', '/register?role=provider', '/forgot-password']
PAGES_CLIENT = ['/', '/categories', '/services', '/providers', '/providers/3', '/jobs', '/how-it-works', '/bookings', '/bookings/105/pay', '/bookings/105', '/messages', '/account', '/settings', '/providers/3/book', '/jobs/new', '/saved', '/notifications']

async def overflow(pg):
    return await pg.evaluate('document.documentElement.scrollWidth - document.documentElement.clientWidth')

async def login(pg, email):
    await pg.goto(B + '/login'); await pg.fill('#email', email); await pg.fill('#password', 'servease123')
    await pg.click('#login-form button[type=submit]'); await pg.wait_for_load_state()

async def main():
    async with async_playwright() as p:
        b = await p.chromium.launch()
        errs = []
        phone = dict(viewport={'width': 390, 'height': 844}, is_mobile=True, has_touch=True, device_scale_factor=2)

        # 1. Phone, signed out: splash, intro slides, welcome, account type
        ctx = await b.new_context(**phone); pg = await ctx.new_page(); pg.on('pageerror', lambda e: errs.append(str(e)))
        await pg.goto(B + '/services')
        check('/welcome' in pg.url, 'first visit: any page opens the intro')
        check(await pg.is_visible('.splash'), 'intro starts with a splash screen')
        await pg.wait_for_timeout(1800)
        check(not await pg.is_visible('.tabbar'), 'no app tab bar before logging in')
        await pg.click('#ob-1 [data-ob-next]'); await pg.wait_for_timeout(800)
        i = await pg.eval_on_selector('[data-ob-track]', 'e => Math.round(e.scrollLeft / e.clientWidth)')
        check(i == 1, 'intro: Next goes to slide 2')
        await pg.click('#ob-2 [data-ob-skip]'); await pg.wait_for_timeout(800)
        check(await pg.is_visible('#ob-start >> text=Log in') and await pg.is_visible('#ob-start >> text=Create account'), 'intro: Skip jumps to Log in / Create account')
        await pg.click('#ob-start >> text=Create account'); await pg.wait_for_load_state()
        check(await pg.is_visible('.role-option:has-text("Customer")') and await pg.is_visible('.role-option:has-text("Service provider")'), 'sign-up starts with Customer or Service provider')
        await pg.click('.role-option:has-text("Service provider")'); await pg.wait_for_load_state()
        check(await pg.get_attribute('input[name=role]', 'value') == 'provider' and await pg.is_visible('.role-badge'), 'sign-up form keeps the chosen account type')
        await pg.goto(B + '/bookings')
        check('/login' in pg.url, 'returning visitor: pages go straight to log in')
        for path in PAGES_GUEST:
            await pg.goto(B + path)
            o = await overflow(pg)
            check(o <= 0, f'phone {path}: no sideways scrolling ({o}px)')
        await ctx.close()

        # 1b. Phone, customer browsing: home, categories, services, pros
        ctx = await b.new_context(**phone); pg = await ctx.new_page(); pg.on('pageerror', lambda e: errs.append(str(e)))
        await login(pg, 'client@servease.test')
        await pg.goto(B + '/')
        check(await pg.is_visible('.tabbar'), 'phone: bottom tab bar is shown')
        check(await pg.is_visible('.topbar .brand') and await pg.is_visible('.topbar .user-chip-phone') and not await pg.is_visible('.topbar .user-menu'), 'phone header: logo, bell and avatar (no extra menu; the tab bar navigates)')
        check(await pg.is_visible('.topbar .loc-chip') and await pg.is_visible('#top-q'), 'phone header: location and search under the logo')
        check(await pg.is_visible('.home-banner .banner-search') and await pg.is_visible('.home-banner .banner-art'), 'phone home: blue banner with search and the mascot')
        check(await pg.eval_on_selector_all('.banner-trust li', 'e => e.length') == 3, 'phone home: three trust points in the banner')
        check(not await pg.is_visible('.footer'), 'phone: website footer hidden in app mode')
        cols = await pg.eval_on_selector('.cat-row', 'e => getComputedStyle(e).gridTemplateColumns.split(" ").length')
        check(cols == 3, f'phone home: categories as three cards per row ({cols})')
        check(await pg.eval_on_selector_all('.near-row .near-card', 'e => e.length') >= 4, 'phone home: Near you cards')
        sw = await pg.eval_on_selector('.near-row', 'e => e.scrollWidth > e.clientWidth')
        check(sw, 'phone home: Near you row swipes sideways')
        check(await pg.eval_on_selector_all('.near-card img', 'e => e.length') >= 1, 'phone home: Near you cards have photos')
        await pg.click('.tab-item:has-text("Services")'); await pg.wait_for_load_state()
        check('/services' in pg.url and await pg.is_visible('.phone-title h1') and await pg.eval_on_selector_all('.cat-circle', 'e => e.length') >= 9, 'Services tab: compact title and round category buttons')
        await pg.click('.cat-circle:has-text("Aircon")'); await pg.wait_for_load_state()
        check('category=aircon' in pg.url and 'is-active' in (await pg.get_attribute('.tab-item:has-text("Services")', 'class')), 'a category opens its services, tab stays on Services')
        await pg.goto(B + '/categories')
        check(await pg.eval_on_selector_all('.cat-card', 'e => e.length') >= 8, 'categories page lists every trade')
        await pg.goto(B + '/services?category=aircon')
        check(await pg.eval_on_selector_all('.svc-card', 'e => e.length') >= 1, 'phone services: service cards for the category')
        check(await pg.is_visible('.svc-card .svc-price'), 'service cards show a clear price')
        cols = await pg.eval_on_selector('.svc-grid', 'e => getComputedStyle(e).gridTemplateColumns.split(" ").length')
        check(cols == 1, f'phone services: one card per row with the photo on the left ({cols})')
        check(await pg.is_visible('.svc-card .svc-media img') and await pg.is_visible('.svc-card .svc-rate'), 'service cards: photo with the rating')
        check(await pg.is_visible('.phone-tools [data-filters-toggle]') and await pg.is_visible('.phone-tools .sort-select'), 'phone services: Filters and Sort under the categories')
        check(not await pg.query_selector('.svc-card .btn'), 'service cards have no extra buttons (the whole card is the link)')
        await pg.click('.svc-card >> nth=0'); await pg.wait_for_load_state()
        check('/providers/' in pg.url and await pg.is_visible('.service-row.is-picked'), 'tapping a service opens the pro with it highlighted')
        await pg.goto(B + '/providers')
        check(not await pg.is_visible('.filters-card'), 'phone pros: filters start hidden')
        await pg.click('[data-filters-toggle]'); await pg.wait_for_timeout(600)
        box = await pg.eval_on_selector('.filters-card', 'e => e.getBoundingClientRect().bottom')
        check(await pg.is_visible('.filters-card') and abs(box - 844) < 2, 'phone services: filter button opens a bottom sheet')
        await pg.click('.radio-row:has-text("Plumbing")'); await pg.click('.filter-actions button'); await pg.wait_for_load_state()
        check('category=plumbing' in pg.url, 'filter sheet applies the category')
        n = await pg.eval_on_selector_all('.pro-card', 'e => e.length')
        check(n >= 1 and 'Plumbing' in await pg.inner_text('h1'), f'filtered list shows plumbing pros ({n})')
        cols = await pg.eval_on_selector('.pro-grid', 'e => getComputedStyle(e).gridTemplateColumns.split(" ").length')
        check(cols == 2, 'phone pros: two-column grid')
        await ctx.close()

        # 2. Phone, customer
        ctx = await b.new_context(**phone); pg = await ctx.new_page(); pg.on('pageerror', lambda e: errs.append(str(e)))
        await login(pg, 'client@servease.test')
        tabs = await pg.eval_on_selector_all('.tab-item .tab-label', 'e => e.map(x => x.textContent)')
        check(tabs == ['Home', 'Services', 'Bookings', 'Inbox', 'Profile'], f'phone customer tabs {tabs}')
        for path in PAGES_CLIENT:
            await pg.goto(B + path)
            o = await overflow(pg)
            check(o <= 0, f'phone {path}: no sideways scrolling ({o}px)')
        await pg.goto(B + '/bookings')
        check('is-active' in (await pg.get_attribute('.tab-item:has-text("Bookings")', 'class')), 'tab bar highlights the current tab')
        check(not await pg.is_visible('.appbar'), 'tab screens keep the main header')
        await pg.click('.stub-list .stub >> nth=0'); await pg.wait_for_load_state()
        check(await pg.is_visible('.appbar-back') and (await pg.inner_text('.appbar-title')) == 'Booking details' and not await pg.is_visible('.topbar .brand'), 'detail screens get an app bar: back arrow and title')
        await pg.click('[data-back]'); await pg.wait_for_load_state()
        check(pg.url.rstrip('/').endswith('/bookings'), 'app bar back returns to the list')
        cdp = await ctx.new_cdp_session(pg)
        errs_install = (await cdp.send('Page.getInstallabilityErrors')).get('installabilityErrors')
        check(errs_install == [], f'Chrome sees the site as an installable app {errs_install}')
        await pg.wait_for_timeout(1200)
        sw = await pg.evaluate("navigator.serviceWorker.getRegistrations().then(r => r.some(x => x.active || x.installing || x.waiting))")
        check(sw, 'service worker registered')
        vt = await pg.evaluate("CSS.supports('view-transition-name: a') && 'onpagereveal' in window")
        check(vt, 'browser supports the app-style page transitions')
        await pg.click('.tab-item:has-text("Profile")'); await pg.wait_for_load_state()
        check(await pg.is_visible('.profile-card') and await pg.is_visible('.menu-row:has-text("Saved pros")'), 'Profile tab lists account links')
        await pg.goto(B + '/bookings/105')
        await pg.click('#payment a:has-text("Record a payment")'); await pg.wait_for_load_state()
        check('/bookings/105/pay' in pg.url and await pg.is_visible('.pay-row:has-text("GCash")'), 'payment screen lists the methods')
        await pg.click('.pay-row:has-text("Maya")')
        check(await pg.is_checked('input[name=method][value=maya]'), 'tapping a payment row selects it')
        await pg.click('.pay-row:has(input[value=cash])')
        check(not await pg.is_visible('#reference'), 'cash hides the reference number field')
        await pg.click('[data-pay-submit]'); await pg.wait_for_load_state()
        check('/bookings/105' in pg.url and 'cash' in (await pg.inner_text('#payment')).lower(), 'Continue records the payment and returns to the booking')
        await ctx.close()

        # 3. Laptop
        ctx = await b.new_context(viewport={'width': 1440, 'height': 900}); pg = await ctx.new_page(); pg.on('pageerror', lambda e: errs.append(str(e)))
        await pg.goto(B + '/')
        check('/welcome' in pg.url, 'laptop: first visit opens the intro too')
        await pg.wait_for_timeout(1600)
        cols = await pg.eval_on_selector('#ob-1', 'e => getComputedStyle(e).gridTemplateColumns.split(" ").length')
        check(cols == 2, 'laptop intro: picture and text side by side')
        await pg.goto(B + '/login')
        check(await pg.is_visible('.auth-side'), 'laptop login: split screen with the brand panel')
        await login(pg, 'client@servease.test')
        await pg.goto(B + '/')
        check(not await pg.is_visible('.tabbar'), 'laptop: no tab bar')
        check(await pg.is_visible('.top-search') and await pg.is_visible('.loc-chip'), 'laptop: top bar has location and search')
        check(await pg.is_visible('.home-banner') and await pg.is_visible('.side-card'), 'laptop home: blue banner beside the next booking')
        check(await pg.is_visible('.home-banner .banner-art') and await pg.is_visible('.home-banner .banner-go'), 'laptop home: banner has the mascot and a blue Search button')
        check(await pg.is_visible('.top-link.is-active:has-text("Home")'), 'laptop: the current page is underlined in the top bar')
        check(not await pg.query_selector('.cat-row img') and await pg.is_visible('.cat-row .cat-icon svg.cat-art-line'), 'categories: line icons on soft-blue tiles')
        check(await pg.eval_on_selector_all('.near-row .near-card img', 'e => e.length') >= 1, 'laptop home: Near you cards have photos')
        cols = await pg.eval_on_selector('.cat-row', 'e => getComputedStyle(e).gridTemplateColumns.split(" ").length')
        check(cols == 8, f'laptop home: 8 category cards in one row ({cols})')
        cols = await pg.eval_on_selector('.near-row', 'e => getComputedStyle(e).gridTemplateColumns.split(" ").length')
        check(cols == 4, 'laptop home: Near you in a 4-column row')
        await pg.fill('#top-q', 'leak'); await pg.press('#top-q', 'Enter'); await pg.wait_for_load_state()
        check('q=leak' in pg.url and '/services' in pg.url, 'top search lands on the services list')
        await pg.goto(B + '/services')
        check(await pg.is_visible('.filters-card'), 'laptop services: filter sidebar visible')
        cols = await pg.eval_on_selector('.svc-grid', 'e => getComputedStyle(e).gridTemplateColumns.split(" ").length')
        check(cols == 3, f'laptop services: service cards in a 3-column grid ({cols})')
        check(await pg.is_visible('.list-hero h1') and await pg.is_visible('.list-hero-lead'), 'laptop services: header with title and a line of text')
        check(await pg.is_visible('.cat-rail .rail-chip.is-active'), 'laptop services: category rail with the current category')
        check(await pg.is_visible('.svc-card .svc-media img') and await pg.is_visible('.svc-card .svc-rate') and await pg.is_visible('.svc-card .svc-go') and await pg.is_visible('.svc-card .card-save'), 'laptop services: photo cards with rating, heart and arrow')
        check(await pg.is_visible('.list-hero-eyebrow:has-text("Our services")') and await pg.is_visible('.list-hero-mosaic'), 'laptop services: "Our services" header with trade photos')
        check(await pg.is_visible('.star-row:has-text("4.5+")') and await pg.is_visible('.pick:has-text("Today")'), 'laptop services: rating and availability filters')
        await pg.goto(B + '/services?category=aircon')
        await pg.click('.results-tools .segmented-nav a:has-text("Pros")'); await pg.wait_for_load_state()
        check('/providers' in pg.url and 'category=aircon' in pg.url, 'Services/Pros switch keeps the category')
        await pg.goto(B + '/services')
        await pg.goto(B + '/providers')
        check(await pg.is_visible('.pro-lines .pro-line') and not await pg.is_visible('.pro-grid'), 'laptop pros: detailed pro rows instead of the phone grid')
        await pg.goto(B + '/services')
        body = await pg.evaluate('getComputedStyle(document.body).fontFamily')
        h1 = await pg.eval_on_selector('h1', 'e => getComputedStyle(e).fontFamily')
        check(body.startswith('"Plus Jakarta Sans"') and 'Jakarta' in h1, f'fonts: Plus Jakarta Sans for text and headings')
        check(await pg.evaluate("document.fonts.check('16px \"Plus Jakarta Sans\"')"), 'Plus Jakarta Sans font loaded')
        await pg.goto(B + '/')
        check(await pg.is_visible('.side-card .side-title:has-text("Your next booking")'), 'laptop home: next booking card for a customer')
        check(await pg.is_visible('.reminder-pay') and await pg.is_visible('.reminder-review'), 'laptop home: payment and review reminders for a customer')
        check(await pg.eval_on_selector_all('.pro-tile', 'e => e.length') == 4, 'laptop home: top pros as cards with View profile')
        await pg.goto(B + '/dashboard'); await pg.wait_for_load_state()
        check(pg.url.rstrip('/') == B, 'customers have no dashboard: /dashboard goes to Home')
        await pg.goto(B + '/bookings')
        check(not await pg.query_selector('.sidenav'), 'one navigation: no sidebar next to the top bar')
        await pg.goto(B + '/bookings/105')
        check(await pg.is_visible('.card-footer >> text=Cancel booking') and 'service fee' not in (await pg.inner_text('#payment')).lower(), 'booking: cancel sits in the details card, no ₱0 fee row')
        await pg.goto(B + '/')
        await pg.click('.user-menu > .user-chip'); await pg.click('.dropdown-menu [data-theme-toggle]')
        theme = await pg.evaluate('document.documentElement.dataset.theme')
        await pg.reload()
        theme2 = await pg.evaluate('document.documentElement.dataset.theme')
        check(theme == 'dark' and theme2 == 'dark', 'dark mode toggles and is remembered')
        await ctx.close()

        check(not errs, f'no JavaScript errors {errs[:3]}')
        await b.close()
    print('\n'.join(res)); print(sum(r.startswith('✓') for r in res), 'passed,', sum(r.startswith('✗') for r in res), 'failed')

asyncio.run(main())
